// The TypeScript half of the codegen chain.
//
//   api/schema/*.py  (Pydantic — hand-written, the source of truth)
//     -> uv run python -m scripts.export_schema     (JSON Schema, on a pipe)
//     -> this file
//     -> web/src/schema/generated/schema.ts         (Zod 4 + inferred types)
//
// Without a fail-on-diff check, "one source of truth" is a claim rather than a
// fact: the drift arrives through a hand-edit to generated TypeScript that
// looks entirely reasonable in review. `--check` is that check, and it runs in
// both pre-commit gates and in CI, where it cannot be skipped with --no-verify.
//
//   pnpm schema:generate   write
//   pnpm schema:check      fail on any difference
//
// WHY THE EMITTER IS OURS. json-schema-to-zod was tried first and pinned in
// phase 00 precisely so this would be discovered here rather than in phase 01:
// it does not resolve `$ref`, so every member of the nested tagged union came
// out as `z.any()` and every character cap was dropped. A validator that
// silently accepts anything is worse than no validator. The subset of JSON
// Schema that Pydantic actually emits is small and closed, so it is emitted
// here — and `unsupported()` throws rather than degrading, which is the single
// property that makes this safe to own.
//
// Types come from `z.infer`, so the schema and its type cannot disagree. That
// is the same property `z.infer` gave inside one language before the split.
//
// docs/coderules/python.md -> "The schema is the source of truth"

import { execFileSync } from 'node:child_process';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import prettier from 'prettier';

const WEB = join(dirname(fileURLToPath(import.meta.url)), '..');
// ponytail: sibling directory in one repo. When `render` and the fetch worker
// arrive in v2 there is a second TypeScript consumer and this becomes a
// published @d-design/schema built in api's CI. Until then, a package with no
// consumers is a release process with no purpose.
const API = join(WEB, '..', 'api');
const OUT = join(WEB, 'src', 'schema', 'generated', 'schema.ts');

const HEADER = `// GENERATED by web/scripts/generate-schema.mjs — DO NOT EDIT.
//
// Source of truth: api/schema/*.py. Change the Pydantic model, run
// \`pnpm schema:generate\`, and commit both in one commit. A hand-edit here
// fails the gate, and it is the only door left open for schema drift.

import { z } from 'zod';
`;

// --------------------------------------------------------------------------
// JSON Schema -> Zod
// --------------------------------------------------------------------------

const unsupported = (node, why) => {
  throw new Error(
    `generate-schema: ${why}\n${JSON.stringify(node, null, 2)}\n\n` +
      `Extend the emitter rather than loosening it. A construct that falls ` +
      `through to a permissive default is a validator that accepts anything.`,
  );
};

const refName = (ref) => {
  const m = /^#\/\$defs\/(.+)$/.exec(ref);
  if (!m) unsupported({ $ref: ref }, `only #/$defs/ refs are supported`);
  return m[1];
};

const varName = (name) => `${name.charAt(0).toLowerCase()}${name.slice(1)}Schema`;

const lit = (v) => JSON.stringify(v);

/** One JSON Schema node to one Zod expression. */
function toZod(node) {
  if (node === true) unsupported(node, 'a bare `true` schema accepts anything');
  if (typeof node !== 'object' || node === null) unsupported(node, 'not a schema object');

  if (node.$ref) return varName(refName(node.$ref));

  // Pydantic wraps a $ref in allOf when it attaches field-level metadata.
  if (node.allOf) {
    if (node.allOf.length !== 1) unsupported(node, 'allOf with more than one branch');
    return withDefault(toZod(node.allOf[0]), node);
  }

  if (node.oneOf || node.anyOf) {
    const branches = node.oneOf ?? node.anyOf;
    const discriminator = node.discriminator?.propertyName;
    if (discriminator) {
      const members = branches.map(toZod).join(', ');
      return withDefault(
        `z.discriminatedUnion(${lit(discriminator)}, [${members}])`,
        node,
      );
    }
    // `X | None` is Pydantic's optional-with-null, and Zod says it better.
    const nulls = branches.filter((b) => b.type === 'null');
    const rest = branches.filter((b) => b.type !== 'null');
    if (nulls.length === 1 && rest.length === 1) {
      return withDefault(`${toZod(rest[0])}.nullable()`, node);
    }
    return withDefault(`z.union([${branches.map(toZod).join(', ')}])`, node);
  }

  if ('const' in node) return withDefault(`z.literal(${lit(node.const)})`, node);

  if (node.enum) {
    const allStrings = node.enum.every((v) => typeof v === 'string');
    const expr = allStrings
      ? `z.enum([${node.enum.map(lit).join(', ')}])`
      : `z.union([${node.enum.map((v) => `z.literal(${lit(v)})`).join(', ')}])`;
    return withDefault(expr, node);
  }

  switch (node.type) {
    case 'string': {
      // Zod 4 spellings: the `.uuid()`/`.datetime()` string methods are the
      // deprecated v3 forms and these are their replacements.
      let expr = 'z.string()';
      if (node.format === 'uuid') expr = 'z.uuid()';
      else if (node.format === 'date-time') expr = 'z.iso.datetime()';
      else if (node.format === 'uri') expr = 'z.url()';
      if (typeof node.minLength === 'number') expr += `.min(${node.minLength})`;
      if (typeof node.maxLength === 'number') expr += `.max(${node.maxLength})`;
      if (node.pattern) expr += `.regex(new RegExp(${lit(node.pattern)}))`;
      return withDefault(expr, node);
    }
    case 'integer':
    case 'number': {
      let expr = node.type === 'integer' ? 'z.int()' : 'z.number()';
      if (typeof node.minimum === 'number') expr += `.min(${node.minimum})`;
      if (typeof node.maximum === 'number') expr += `.max(${node.maximum})`;
      if (typeof node.exclusiveMinimum === 'number')
        expr += `.gt(${node.exclusiveMinimum})`;
      if (typeof node.exclusiveMaximum === 'number')
        expr += `.lt(${node.exclusiveMaximum})`;
      return withDefault(expr, node);
    }
    case 'boolean':
      return withDefault('z.boolean()', node);
    case 'null':
      return withDefault('z.null()', node);
    case 'array': {
      if (!node.items) unsupported(node, 'array without `items` accepts anything');
      let expr = `z.array(${toZod(node.items)})`;
      if (typeof node.minItems === 'number') expr += `.min(${node.minItems})`;
      if (typeof node.maxItems === 'number') expr += `.max(${node.maxItems})`;
      return withDefault(expr, node);
    }
    case 'object': {
      const required = new Set(node.required ?? []);
      const entries = Object.entries(node.properties ?? {}).map(([key, prop]) => {
        const expr = toZod(prop);
        return `${lit(key)}: ${required.has(key) ? expr : `${expr}.optional()`}`;
      });
      // Map `additionalProperties` faithfully rather than assuming. Pydantic's
      // default ignores an unknown key and Zod's `z.object` strips one — the
      // same verdict — but `extra="forbid"` must become `z.strictObject` or
      // the two languages disagree on exactly the input worth disagreeing
      // about. schema/base.py forbids, so this takes the strict branch.
      const extra = node.additionalProperties;
      if (extra !== false && extra !== undefined) {
        unsupported(
          node,
          'additionalProperties as a schema, or `true`, is not supported',
        );
      }
      const object = extra === false ? 'z.strictObject' : 'z.object';
      return withDefault(`${object}({ ${entries.join(', ')} })`, node);
    }
    default:
      return unsupported(node, `unhandled type ${JSON.stringify(node.type)}`);
  }
}

const withDefault = (expr, node) =>
  'default' in node ? `${expr}.default(${lit(node.default)})` : expr;

// --------------------------------------------------------------------------
// Emit
// --------------------------------------------------------------------------

/** Every $def across every exported model, deduplicated. */
function collectDefs(schemas) {
  const defs = {};
  for (const schema of Object.values(schemas)) {
    for (const [name, def] of Object.entries(schema.$defs ?? {})) {
      const seen = defs[name];
      if (seen && JSON.stringify(seen) !== JSON.stringify(def)) {
        throw new Error(`generate-schema: two different definitions named ${name}`);
      }
      defs[name] = def;
    }
  }
  return defs;
}

/** Definitions before the definitions that reference them. */
function ordered(defs) {
  const out = [];
  const done = new Set();
  const active = new Set();
  const refs = (node) => {
    const found = [];
    const walk = (n) => {
      if (Array.isArray(n)) return n.forEach(walk);
      if (!n || typeof n !== 'object') return;
      if (typeof n.$ref === 'string') found.push(refName(n.$ref));
      Object.values(n).forEach(walk);
    };
    walk(node);
    return found;
  };
  const visit = (name) => {
    if (done.has(name)) return;
    if (active.has(name)) {
      // Zod handles this with z.lazy() and an explicit type annotation, and
      // nothing in the Scene tree is recursive. Refuse rather than emit
      // something that looks right and blows the stack.
      throw new Error(`generate-schema: recursive definition ${name} is not supported`);
    }
    active.add(name);
    for (const dep of refs(defs[name])) visit(dep);
    active.delete(name);
    done.add(name);
    out.push(name);
  };
  Object.keys(defs).sort().forEach(visit);
  return out;
}

function render(schemas) {
  const defs = collectDefs(schemas);
  const parts = [HEADER];

  for (const name of ordered(defs)) {
    parts.push(`export const ${varName(name)} = ${toZod(defs[name])};`);
    parts.push(`export type ${name} = z.infer<typeof ${varName(name)}>;`);
  }

  for (const [name, schema] of Object.entries(schemas)) {
    const { $defs: _defs, ...root } = schema;
    parts.push(`export const ${varName(name)} = ${toZod(root)};`);
    parts.push(`export type ${name} = z.infer<typeof ${varName(name)}>;`);
  }

  return parts.join('\n\n');
}

// --------------------------------------------------------------------------

const check = process.argv.includes('--check');

const raw = execFileSync('uv', ['run', 'python', '-m', 'scripts.export_schema'], {
  cwd: API,
  encoding: 'utf8',
  maxBuffer: 32 * 1024 * 1024,
});
const schemas = JSON.parse(raw);

const next = await prettier.format(render(schemas), {
  ...(await prettier.resolveConfig(OUT)),
  parser: 'typescript',
});

let current = null;
try {
  current = readFileSync(OUT, 'utf8');
} catch {
  current = null; // a missing file is a diff; the message below says so
}

if (check) {
  if (current !== next) {
    console.error(
      `schema drift: ${OUT} does not match what api/schema/*.py generates.\n` +
        `Run \`pnpm schema:generate\` and commit the result alongside the Pydantic change.`,
    );
    process.exit(1);
  }
} else {
  mkdirSync(dirname(OUT), { recursive: true });
  writeFileSync(OUT, next);
  console.log(`schema: generated ${Object.keys(schemas).join(', ')}`);
}
