// One Chromium, reused across requests.
//
// Launching a browser per screenshot is the difference between the visual
// verification loop in phase 09 costing latency and costing a minute — a launch
// is roughly a second, a page is roughly ten milliseconds. So the browser is a
// singleton and the *page* is what is created and closed per request.
//
// A page per request rather than a pooled page, deliberately: a reused page
// carries the last render's scroll position, its fonts, its custom properties
// and anything a `Slot` iframe did to it. Pooling those would trade a
// negligible cost for a class of "the screenshot has the previous scene in it"
// bug that is invisible until someone looks at a hundred of them.

import { chromium, type Browser, type Page } from 'playwright';

let browser: Browser | null = null;
let launching: Promise<Browser> | null = null;

/** Concurrent first calls must not each launch a browser, so the *promise* is
 * memoized rather than the result — two requests arriving before the first
 * launch resolves would otherwise leave one Chromium orphaned with nothing
 * holding a reference to close it. */
export async function getBrowser(): Promise<Browser> {
  if (browser !== null && browser.isConnected()) return browser;
  launching ??= chromium
    .launch({
      // **Stated, not inherited.** This said "never `--no-sandbox`" while
      // Playwright added that exact flag on every launch, because
      // `chromiumSandbox` defaults to *false* — a comment asserting the
      // opposite of what the code did, which is worse than no comment. Found
      // by building the image and reading `/proc/*/cmdline` inside it, which
      // is the only place the difference is visible.
      //
      // It is `false` deliberately, and the reason is the trust split rather
      // than convenience. Under Docker's default seccomp profile Chromium has
      // no usable sandbox at all: `clone(CLONE_NEWUSER)` is blocked, and the
      // SUID helper modern Chromium no longer accepts as a substitute. The
      // only ways to a real sandbox are a custom seccomp profile or
      // `seccomp=unconfined` — verified: with `unconfined`, `chromiumSandbox:
      // true` launches cleanly.
      //
      // Trading Docker's syscall filter for Chromium's sandbox is the right
      // trade for a process rendering *hostile* pages, and the wrong one here.
      // This service renders a schema-validated scene tree carrying no
      // presentational values — trusted input, generated by us, from our own
      // database. The fetch worker is the one that renders attackers' pages,
      // and `docs/security/testing.md`'s sandbox assertion is written for it.
      //
      // **The fetch worker must not copy this line.** It needs both layers,
      // which means the seccomp profile, and that is v3's problem to solve
      // rather than a default to inherit from here.
      chromiumSandbox: false,
      args: ['--disable-dev-shm-usage'],
    })
    .then((b) => {
      browser = b;
      launching = null;
      return b;
    });
  return launching;
}

export async function withPage<T>(
  viewport: { width: number; height: number },
  fn: (page: Page) => Promise<T>,
): Promise<T> {
  const context = await (await getBrowser()).newContext({ viewport });
  try {
    return await fn(await context.newPage());
  } finally {
    // A context, not just a page: closing the context is what actually
    // releases storage, service workers and any frame the page opened.
    await context.close();
  }
}

export async function closeBrowser(): Promise<void> {
  await browser?.close();
  browser = null;
}
